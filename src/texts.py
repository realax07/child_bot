def format_duration(total: timedelta) -> str:
    """Длительность в формате ТЗ §7: «4 ч 30 мин», «45 мин», «2 ч», «0 мин»."""
    minutes = max(0, round(total.total_seconds() / 60))
    hours, mins = divmod(minutes, 60)
    if hours == 0:
        return f"{mins} мин"
    if mins == 0:
        return f"{hours} ч"
    return f"{hours} ч {mins} мин"


