def hint_awake_text(
    wake_line: str,
    total_line: str,
    position_line: str,
    window_line: str,
    warning_lines: Iterable[str] = (),
) -> str:
    """§7.6: структура ответа бодрствующему (строки §7.6 + предупреждения)."""
    lines = [
        f"Бодрствование с последнего пробуждения: {wake_line}. "
        f"Суммарно за сегодня: {total_line}.",
        position_line,
        "",
        window_line,
    ]
    lines.extend(warning_lines)
    return "\n".join(lines)


